/** Resolve a bundled reference image by its stable, version-specific ID. */
export function getReferenceFloorPlan(floorPlanId: string): MarketFloorPlan | undefined {
  return REFERENCE_FLOOR_PLANS.find((plan) => plan.floor_plan_id === floorPlanId);
}

const REFERENCE_FIELDS = [
  'floor_plan_id', 'location_id', 'name', 'image_url', 'width', 'height',
  'source_label', 'source_url', 'is_demo',
] as const;

/** Require the exact bundled image and all canonical metadata fields. */
export function isReferenceFloorPlan(value: unknown): value is MarketFloorPlan {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return false;
  const input = value as Record<string, unknown>;
  if (typeof input.floor_plan_id !== 'string') return false;
  const reference = getReferenceFloorPlan(input.floor_plan_id);
  return !!reference && REFERENCE_FIELDS.every((field) => Object.prototype.hasOwnProperty.call(input, field) && input[field] === reference[field]);
}
